    info = _parse_ffmpeg_banner(banner)
    assert "duration" not in info
    # The other fields still parse — one miss degrades one field.
    assert info["codec"] == "h264"
    assert info["container"] == "mov,mp4,m4a,3gp,3g2,mj2"


