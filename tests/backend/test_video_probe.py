def _solid(color, size=(320, 180)) -> Image.Image:
    return Image.new("RGB", size, color)


def test_a_solid_frame_carries_no_information():
    """Black, and a slate of any other brightness, both score zero."""
    assert _frame_entropy(_solid((0, 0, 0))) == 0.0
    assert _frame_entropy(_solid((128, 128, 128))) == 0.0
    assert _frame_entropy(_solid((40, 90, 200))) == 0.0


def test_titles_over_black_score_below_the_floor():
    """Two levels carry almost nothing, however sharp the text.

    This is the frame a fixed seek lands on in a film with a title sequence,
    and the reason the score is entropy rather than contrast: the standard
    deviation of this frame is enormous.
    """
    frame = _solid((0, 0, 0))
    for x in range(70, 250, 26):
        frame.paste(_solid((255, 255, 255), (16, 14)), (x, 86))
    assert _frame_entropy(frame) < FRAME_ENTROPY_FLOOR


def test_a_dark_but_real_scene_scores_above_the_floor():
    """A night scene must survive. It is almost entirely dark, so a
    dark-pixel count would reject it; what separates it from a title card is
    that it has tone everywhere rather than two levels."""
    frame = Image.new("RGB", (320, 180))
    frame.putdata(
        [(v // 8, v // 8, max(0, v // 8 - 2)) for v in range(180) for _ in range(320)]
    )
    assert _frame_entropy(frame) > FRAME_ENTROPY_FLOOR


def test_ordinary_content_scores_well_above_the_floor():
    """A daylight frame is not near the threshold; it is nowhere near it."""
    frame = Image.new("RGB", (320, 180))
    frame.putdata(
        [
            (60 + x // 3, 90 + y // 4, 200 - x // 4)
            for y in range(180)
            for x in range(320)
        ]
    )
    assert _frame_entropy(frame) > 4 * FRAME_ENTROPY_FLOOR


def test_an_unmeasurable_frame_is_always_kept():
    """The score is an optimisation hint; it must never lose a frame."""

    class Hostile:
        def convert(self, _mode):
            raise ValueError("no")

    assert _frame_entropy(Hostile()) == float("inf")


def test_the_floor_sits_between_the_junk_and_content_bands():
    """Calibrated against a labelled corpus of synthetic-but-realistic frames
    and real encodes. Junk measured 0.0 (black) to 0.65 (a dense end-credit
    crawl); the lowest real content measured 1.07 (an overcast snowfield).
    A floor outside that gap is a mis-set threshold, not a preference."""
    assert 0.66 <= FRAME_ENTROPY_FLOOR <= 1.05


