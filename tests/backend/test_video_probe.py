def _record_attempts(monkeypatch) -> list[tuple[float | None, float]]:
    """Capture the -ss value and the timeout of every ffmpeg attempt."""
    attempts: list[tuple[float | None, float]] = []
    real = video_module._run_ffmpeg

    def spy(args, timeout):
        seek = float(args[args.index("-ss") + 1]) if "-ss" in args else None
        attempts.append((seek, timeout))
        return real(args, timeout)

    monkeypatch.setattr(video_module, "_run_ffmpeg", spy)
    return attempts


def _seeks(attempts) -> list[float | None]:
    return [seek for seek, _timeout in attempts]


@requires_ffmpeg
def test_a_good_frame_costs_exactly_one_ffmpeg_run(monkeypatch):
    """The default path, on the shape of file most of a collection is: the
    retries must not become a tax on every video."""
    attempts = _record_attempts(monkeypatch)

    frame, _info = extract_video_frame(media_fixture_path("scene.mp4"))

    assert _seeks(attempts) == [FRAME_SEEK_SECONDS]
    assert _frame_entropy(frame) >= FRAME_ENTROPY_FLOOR


