"""Still-frame extraction and banner probing.

The fixtures under ``test_media/`` are deliberately tiny and purpose-built:

``clip.mp4``     2s @10fps, 64x64 — red for the first second, blue for the
                 second. Shorter than FRAME_SEEK_SECONDS, so it also proves
                 the walk back towards the start reaches 1.0s.
``short.mp4``    0.2s — shorter than every seek, so it reaches the no-seek
                 attempt.
``clip.webm``    a second container.
``rotated.mp4``  encoded 64x32 with a 90-degree display matrix, so the decoded
                 frame is 32x64 and the banner's dimensions are wrong.
``broken.mp4``   a truncated ``clip.mp4``.
``titles.mp4``   12s @10fps — a title card (white marks on black, ~3% of the
                 frame, as a real card is) for the first 6s, then a scene.
                 The frame at FRAME_SEEK_SECONDS is the card, so it exercises
                 the deeper retry.
``scene.mp4``    8s, that same scene throughout: the frame at
                 FRAME_SEEK_SECONDS is already good.
``outro.mp4``    10s — the scene for 4s, then black. The good frame is
                 *earlier* than the first attempt, so it exercises the walk
                 back towards the start.
``dark.mp4``     8s, black throughout: no offset has anything to find, and the
                 file must still be indexed.

The last four are 320x180 (a 64x64 frame is too small for a title card to
measure like a real one) and were generated by rendering PIL frames and
piping them to the bundled ffmpeg as image2pipe PNGs (``-c:v libx264
-pix_fmt yuv420p -g 10``).
"""

