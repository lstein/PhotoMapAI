@requires_ffmpeg
def test_a_stalled_seek_skips_straight_to_the_no_seek_attempt(monkeypatch):
    """Seeking is what stalls on a slow mount, so retrying a shallower seek
    just buys a second timeout. A wedged file must cost two attempts, not one
    per rung of the ladder."""
    real = video_module._run_ffmpeg

    def stall_the_seek(args, timeout):
        if "-ss" in args:
            return None  # what _run_ffmpeg returns on a timeout
        return real(args, timeout)

    monkeypatch.setattr(video_module, "_run_ffmpeg", stall_the_seek)
    attempts = _record_attempts(monkeypatch)  # outermost, so it sees every attempt

    frame, _info = extract_video_frame(media_fixture_path("clip.mp4"))

    assert _seeks(attempts) == [FRAME_SEEK_SECONDS, None]
    r, _g, _b = frame.getpixel((32, 32))
    assert r > 200, "the no-seek attempt returns the red opening frame"


@requires_ffmpeg
def test_the_whole_file_is_bounded_by_twice_the_timeout(monkeypatch):
    """``video_cache.ensure`` and the thumbnail route both size their own
    locking and threadpool behaviour on this ceiling, so the ladder may not
    raise it however many rungs it grows."""
    attempts = _record_attempts(monkeypatch)
    clock = iter([0.0, 0.0, 55.0, 90.0, 130.0, 200.0, 300.0])
    last = [0.0]

    class SlowClock:
        def monotonic(self):
            last[0] = next(clock, last[0] + 100.0)
            return last[0]

    monkeypatch.setattr(video_module, "time", SlowClock())

    extract_video_frame(media_fixture_path("dark.mp4"))

    # The clock reports 0s, 55s and 90s elapsed at the three attempt sites,
    # against a 120s budget: full timeouts while there is room, then whatever
    # is left, then nothing.
    assert [timeout for _seek, timeout in attempts] == [
        FRAME_EXTRACT_TIMEOUT_SECONDS,
        FRAME_EXTRACT_TIMEOUT_SECONDS,
        30.0,
    ]
    assert len(attempts) < MAX_FRAME_ATTEMPTS, "the deadline cut the search short"


